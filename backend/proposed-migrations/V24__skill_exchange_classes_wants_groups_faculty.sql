    student_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    PRIMARY KEY (want_id, student_id),
    CONSTRAINT fk_skill_want_supporter_want FOREIGN KEY (college_id, want_id)
        REFERENCES public.skill_wants (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_want_supporter_student FOREIGN KEY (college_id, student_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);

CREATE TABLE public.skill_want_helpers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    want_id bigint NOT NULL,
    teacher_id bigint NOT NULL,
    message varchar(500) NOT NULL DEFAULT '',
    status varchar(9) NOT NULL DEFAULT 'OFFERED',
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    decided_at timestamptz,
    CONSTRAINT uq_skill_want_helper_once UNIQUE (want_id, teacher_id),
    CONSTRAINT ck_skill_want_helper_status CHECK (status IN ('OFFERED', 'ACCEPTED', 'DECLINED', 'WITHDRAWN')),
    CONSTRAINT ck_skill_want_helper_decided CHECK ((status = 'OFFERED') = (decided_at IS NULL)),
    CONSTRAINT fk_skill_want_helper_want FOREIGN KEY (college_id, want_id)
        REFERENCES public.skill_wants (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_want_helper_teacher FOREIGN KEY (college_id, teacher_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_skill_want_helper_accepted ON public.skill_want_helpers (want_id) WHERE status = 'ACCEPTED';

-- ---- Requests and sessions can come from a post ----

ALTER TABLE public.skill_requests
    ALTER COLUMN offer_id DROP NOT NULL,
    ADD COLUMN want_id bigint,
    ADD CONSTRAINT ck_skill_request_source CHECK ((offer_id IS NULL) <> (want_id IS NULL)),
    ADD CONSTRAINT fk_skill_request_want FOREIGN KEY (college_id, want_id)
        REFERENCES public.skill_wants (college_id, id) ON DELETE RESTRICT;
CREATE UNIQUE INDEX uq_skill_request_want_open ON public.skill_requests (want_id, learner_id)
    WHERE status IN ('REQUESTED', 'ACCEPTED');

ALTER TABLE public.skill_sessions
    ALTER COLUMN offer_id DROP NOT NULL,
    -- Without an offer, only the request's provider (the volunteer who answered a post) teaches.
    ADD CONSTRAINT ck_skill_session_offer CHECK (offer_id IS NOT NULL OR teacher_id = provider_id);

-- ---- Learning groups ----

CREATE TABLE public.skill_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    teacher_id bigint NOT NULL,
    offer_id bigint,
    want_id bigint,
    name varchar(80) NOT NULL,
    conversation_id bigint,
    status varchar(6) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    closed_at timestamptz,
    CONSTRAINT uq_skill_group_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_skill_group_source CHECK ((offer_id IS NULL) <> (want_id IS NULL)),
    CONSTRAINT ck_skill_group_status CHECK (status IN ('ACTIVE', 'CLOSED')),
    CONSTRAINT ck_skill_group_closed CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)),
    CONSTRAINT fk_skill_group_teacher FOREIGN KEY (college_id, teacher_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_group_offer FOREIGN KEY (college_id, offer_id, teacher_id)
        REFERENCES public.skill_offers (college_id, id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_group_want FOREIGN KEY (college_id, want_id)
        REFERENCES public.skill_wants (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_group_chat FOREIGN KEY (college_id, conversation_id)
        REFERENCES public.chat_conversations (college_id, id) ON DELETE RESTRICT
);
-- One active group per offered skill and per post.
CREATE UNIQUE INDEX uq_skill_group_offer_active ON public.skill_groups (offer_id) WHERE status = 'ACTIVE' AND offer_id IS NOT NULL;
CREATE UNIQUE INDEX uq_skill_group_want_active ON public.skill_groups (want_id) WHERE status = 'ACTIVE' AND want_id IS NOT NULL;

CREATE TABLE public.skill_group_members (
    college_id bigint NOT NULL,
    group_id bigint NOT NULL,
    learner_id bigint NOT NULL,
    request_id bigint NOT NULL,
    joined_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    left_at timestamptz,
    PRIMARY KEY (group_id, learner_id),
    CONSTRAINT ck_skill_group_member_times CHECK (left_at IS NULL OR left_at >= joined_at),
    CONSTRAINT fk_skill_group_member_group FOREIGN KEY (college_id, group_id)
        REFERENCES public.skill_groups (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_group_member_request FOREIGN KEY (college_id, request_id)
        REFERENCES public.skill_requests (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_group_member_learner FOREIGN KEY (college_id, learner_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_skill_group_members_learner ON public.skill_group_members (college_id, learner_id) WHERE left_at IS NULL;

CREATE TABLE public.skill_group_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    group_id bigint NOT NULL,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    mode varchar(9) NOT NULL,
    place varchar(300) NOT NULL DEFAULT '',
    status varchar(9) NOT NULL DEFAULT 'SCHEDULED',
    cancel_reason varchar(300),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    completed_at timestamptz,
    cancelled_at timestamptz,
    CONSTRAINT uq_skill_group_session_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_skill_group_session_time CHECK (ends_at > starts_at AND ends_at <= starts_at + interval '4 hours'),
    CONSTRAINT ck_skill_group_session_mode CHECK (mode IN ('ONLINE', 'IN_PERSON')),
    CONSTRAINT ck_skill_group_session_status CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_skill_group_session_shape CHECK (
        (status = 'SCHEDULED' AND completed_at IS NULL AND cancelled_at IS NULL)
     OR (status = 'COMPLETED' AND completed_at IS NOT NULL AND cancelled_at IS NULL)
     OR (status = 'CANCELLED' AND cancelled_at IS NOT NULL AND completed_at IS NULL)),
    CONSTRAINT fk_skill_group_session_group FOREIGN KEY (college_id, group_id)
        REFERENCES public.skill_groups (college_id, id) ON DELETE RESTRICT
);
CREATE INDEX ix_skill_group_sessions_group ON public.skill_group_sessions (college_id, group_id, starts_at);
CREATE INDEX ix_skill_group_sessions_upcoming ON public.skill_group_sessions (starts_at) WHERE status = 'SCHEDULED';

-- ---- Learning from a faculty member ----

CREATE TABLE public.skill_faculty_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    created_by bigint NOT NULL,
    topic varchar(120) NOT NULL,
    details varchar(1000) NOT NULL DEFAULT '',
    audience varchar(7) NOT NULL,
    division_id bigint REFERENCES public.academic_divisions (id) ON DELETE RESTRICT,
    status varchar(9) NOT NULL DEFAULT 'OPEN',
    starts_at timestamptz,
    ends_at timestamptz,
    mode varchar(9),
    place varchar(300),
    reason varchar(300),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    decided_at timestamptz,
    CONSTRAINT uq_skill_faculty_request_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_skill_faculty_request_topic CHECK (length(btrim(topic)) >= 3),
    CONSTRAINT ck_skill_faculty_request_audience CHECK ((audience = 'COLLEGE' AND division_id IS NULL)
        OR (audience = 'CLASS' AND division_id IS NOT NULL)),
    CONSTRAINT ck_skill_faculty_request_status CHECK (status IN ('OPEN', 'ACCEPTED', 'DECLINED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT ck_skill_faculty_request_shape CHECK (
        (status = 'OPEN' AND starts_at IS NULL AND decided_at IS NULL)
     OR (status IN ('ACCEPTED', 'COMPLETED') AND starts_at IS NOT NULL AND ends_at > starts_at
            AND ends_at <= starts_at + interval '4 hours' AND mode IN ('ONLINE', 'IN_PERSON') AND decided_at IS NOT NULL)
     OR (status IN ('DECLINED', 'CANCELLED') AND decided_at IS NOT NULL)),
    CONSTRAINT fk_skill_faculty_request_faculty FOREIGN KEY (college_id, faculty_id)
        REFERENCES public.faculty_profiles (college_id, faculty_id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_faculty_request_creator FOREIGN KEY (college_id, created_by)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_skill_faculty_requests_faculty ON public.skill_faculty_requests (college_id, faculty_id, status, id DESC);
CREATE INDEX ix_skill_faculty_requests_feed ON public.skill_faculty_requests (college_id, status, id DESC);

