-- PROPOSED, NOT APPLIED. Needs the project owner's approval before it is run on any database.
--
-- Skill Exchange version 2. Requires V23. Everything stays inside one college, as in V23.
--
--   skill_offers (new columns)  who may see an offer: the whole college, or only the owner's class (division)
--   skill_wants                 "I want to learn ..." posts, for the class or the college
--   skill_want_comments         the discussion under a post
--   skill_want_supporters       classmates who tapped "Me too"
--   skill_want_helpers          classmates who offered to teach; the poster accepts one
--   skill_requests (changed)    a request now comes from an offered skill OR from an accepted post (offer_id or want_id)
--   skill_sessions (changed)    a session from a post has no offer (the volunteer teaches the post's topic)
--   skill_groups                up to 5 learners learning the same thing from one student, with a group chat
--   skill_group_members         the learners of a group (each through their own accepted request)
--   skill_group_sessions        sessions the teaching student sets for the whole group
--   skill_faculty_requests      students asking a faculty member of their college to teach a topic
--   skill_faculty_request_members  students who joined such a request ("Me too")
--   skill_faculty_notices       the faculty member's notifications about these requests
--   skill_notifications (changed)  new kinds and links to posts, groups and faculty requests
--
-- Existing rows keep their values: every existing offer becomes audience COLLEGE (how V23 already works), and new
-- columns are empty. Two V23 columns become optional (skill_requests.offer_id, skill_sessions.offer_id) so a request
-- can come from a post; every existing row still has them. Every relationship carries college_id in its foreign key.

-- ---- Who can see an offer ----

ALTER TABLE public.skill_offers
    ADD COLUMN audience varchar(7) NOT NULL DEFAULT 'COLLEGE',
    ADD COLUMN division_id bigint REFERENCES public.academic_divisions (id) ON DELETE RESTRICT,
    ADD CONSTRAINT ck_skill_offer_audience CHECK ((audience = 'COLLEGE' AND division_id IS NULL)
        OR (audience = 'CLASS' AND division_id IS NOT NULL));

-- ---- "I want to learn" posts ----

CREATE TABLE public.skill_wants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    student_id bigint NOT NULL,
    title varchar(80) NOT NULL,
    details varchar(1000) NOT NULL DEFAULT '',
    category varchar(12) NOT NULL,
    audience varchar(7) NOT NULL,
    division_id bigint REFERENCES public.academic_divisions (id) ON DELETE RESTRICT,
    status varchar(7) NOT NULL DEFAULT 'OPEN',
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    matched_at timestamptz,
    closed_at timestamptz,
    CONSTRAINT uq_skill_want_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_skill_want_title CHECK (length(btrim(title)) >= 3),
    CONSTRAINT ck_skill_want_category CHECK (category IN ('PROGRAMMING', 'DESIGN', 'LANGUAGES', 'MATHEMATICS',
        'SCIENCE', 'BUSINESS', 'ARTS', 'MUSIC', 'SPORTS', 'ACADEMICS', 'OTHER')),
    CONSTRAINT ck_skill_want_audience CHECK ((audience = 'COLLEGE' AND division_id IS NULL)
        OR (audience = 'CLASS' AND division_id IS NOT NULL)),
    CONSTRAINT ck_skill_want_status CHECK (status IN ('OPEN', 'MATCHED', 'CLOSED')),
    CONSTRAINT ck_skill_want_matched CHECK ((status = 'MATCHED') = (matched_at IS NOT NULL) OR status = 'CLOSED'),
    CONSTRAINT ck_skill_want_closed CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL)),
    CONSTRAINT fk_skill_want_student FOREIGN KEY (college_id, student_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_skill_wants_feed ON public.skill_wants (college_id, status, id DESC);
CREATE INDEX ix_skill_wants_owner ON public.skill_wants (college_id, student_id, id DESC);

CREATE TABLE public.skill_want_comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    want_id bigint NOT NULL,
    author_id bigint NOT NULL,
    body varchar(1000) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    deleted_at timestamptz,
    CONSTRAINT ck_skill_want_comment_body CHECK (deleted_at IS NOT NULL OR body ~ '[^[:space:]]'),
    CONSTRAINT ck_skill_want_comment_deleted CHECK (deleted_at IS NULL OR deleted_at >= created_at),
    CONSTRAINT fk_skill_want_comment_want FOREIGN KEY (college_id, want_id)
        REFERENCES public.skill_wants (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_want_comment_author FOREIGN KEY (college_id, author_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_skill_want_comments ON public.skill_want_comments (college_id, want_id, id);

CREATE TABLE public.skill_want_supporters (
    college_id bigint NOT NULL,
