CREATE FUNCTION public.protect_skill_faculty_notice() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Faculty notices are kept as history' USING ERRCODE = '42501';
    END IF;
    IF (NEW.id, NEW.college_id, NEW.faculty_id, NEW.kind, NEW.event_key, NEW.title, NEW.body, NEW.request_id, NEW.created_at)
       IS DISTINCT FROM
       (OLD.id, OLD.college_id, OLD.faculty_id, OLD.kind, OLD.event_key, OLD.title, OLD.body, OLD.request_id, OLD.created_at)
       OR (OLD.read_at IS NOT NULL AND NEW.read_at IS DISTINCT FROM OLD.read_at) THEN
        RAISE EXCEPTION 'Only an unread notice can be marked as read' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER skill_faculty_notices_history
    BEFORE UPDATE OR DELETE ON public.skill_faculty_notices
    FOR EACH ROW EXECUTE FUNCTION public.protect_skill_faculty_notice();
CREATE TRIGGER skill_faculty_notices_no_truncate
    BEFORE TRUNCATE ON public.skill_faculty_notices
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();

