-- PROPOSED, NOT APPLIED. Needs the project owner's approval before it is run on any database.
--
-- Student groups and chat. Requires V9/V11/V12 (academic_divisions key with program and year) and V13
-- (student_profiles). Adds five tables. No existing table, column or row is changed.
--
--   chat_conversations   a class group (one per division, members follow current enrollment), a study group
--                        created by a student, or a private chat between two students
--   chat_members         who is in a conversation, their role and how far they have read
--   chat_messages        text and/or one file per message; a retried send (same client_key) is stored once
--   chat_blocks          a student blocking another student (no private chat either way)
--   chat_reports         a student's report of a message; the message is then hidden for that student
--
-- Chats are for students only: every row points at student_profiles, and the application has no route through
-- which faculty, College Admins or Super Admins can read conversations, messages or reports.

CREATE TABLE public.chat_conversations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL REFERENCES public.colleges (id) ON DELETE RESTRICT,
    kind varchar(6) NOT NULL,
    name varchar(80),
    description varchar(500) NOT NULL DEFAULT '',
    program_id bigint,
    academic_year_id bigint,
    division_id bigint,
    join_policy varchar(6),
    direct_key varchar(41),
    created_by bigint,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    last_message_at timestamptz,
    archived_at timestamptz,
    CONSTRAINT uq_chat_conversation_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_chat_conversation_kind CHECK (kind IN ('CLASS', 'GROUP', 'DIRECT')),
    CONSTRAINT ck_chat_conversation_shape CHECK (
        (kind = 'CLASS' AND program_id IS NOT NULL AND academic_year_id IS NOT NULL AND division_id IS NOT NULL
            AND name ~ '[^[:space:]]' AND join_policy IS NULL AND direct_key IS NULL AND created_by IS NULL)
     OR (kind = 'GROUP' AND program_id IS NULL AND academic_year_id IS NULL AND division_id IS NULL
            AND name ~ '[^[:space:]]' AND join_policy IN ('OPEN', 'INVITE') AND direct_key IS NULL AND created_by IS NOT NULL)
     OR (kind = 'DIRECT' AND program_id IS NULL AND academic_year_id IS NULL AND division_id IS NULL
            AND name IS NULL AND join_policy IS NULL AND direct_key ~ '^[0-9]+:[0-9]+$' AND created_by IS NOT NULL)),
    CONSTRAINT ck_chat_conversation_times CHECK (archived_at IS NULL OR archived_at >= created_at),
    CONSTRAINT fk_chat_conversation_division FOREIGN KEY (college_id, program_id, academic_year_id, division_id)
        REFERENCES public.academic_divisions (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_chat_conversation_creator FOREIGN KEY (college_id, created_by)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
-- One class group per division, and one private chat per pair of students.
CREATE UNIQUE INDEX uq_chat_class_group ON public.chat_conversations (college_id, division_id) WHERE kind = 'CLASS';
CREATE UNIQUE INDEX uq_chat_direct_pair ON public.chat_conversations (college_id, direct_key) WHERE kind = 'DIRECT';
CREATE INDEX ix_chat_open_groups ON public.chat_conversations (college_id, kind, archived_at) WHERE kind = 'GROUP';

CREATE TABLE public.chat_members (
    college_id bigint NOT NULL,
    conversation_id bigint NOT NULL,
    student_id bigint NOT NULL,
    role varchar(6) NOT NULL DEFAULT 'MEMBER',
    joined_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    left_at timestamptz,
    last_read_message_id bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (conversation_id, student_id),
    CONSTRAINT ck_chat_member_role CHECK (role IN ('OWNER', 'MEMBER')),
    CONSTRAINT ck_chat_member_times CHECK (left_at IS NULL OR left_at >= joined_at),
    CONSTRAINT ck_chat_member_read CHECK (last_read_message_id >= 0),
    CONSTRAINT fk_chat_member_conversation FOREIGN KEY (college_id, conversation_id)
        REFERENCES public.chat_conversations (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_chat_member_student FOREIGN KEY (college_id, student_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_chat_members_student ON public.chat_members (college_id, student_id) WHERE left_at IS NULL;

CREATE TABLE public.chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    conversation_id bigint NOT NULL,
    sender_id bigint NOT NULL,
    client_key uuid NOT NULL,
    body varchar(4000) NOT NULL DEFAULT '',
    attachment_name varchar(200),
    attachment_key uuid UNIQUE,
    attachment_format varchar(4),
    attachment_mime varchar(100),
    attachment_size integer,
    attachment_sha256 char(64),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    deleted_at timestamptz,
    CONSTRAINT uq_chat_message_college_id UNIQUE (college_id, id),
    CONSTRAINT uq_chat_message_client_key UNIQUE (sender_id, client_key),
    CONSTRAINT ck_chat_message_content CHECK (deleted_at IS NOT NULL OR body ~ '[^[:space:]]' OR attachment_key IS NOT NULL),
    CONSTRAINT ck_chat_message_deleted CHECK (deleted_at IS NULL OR (body = '' AND attachment_key IS NULL)),
    CONSTRAINT ck_chat_message_attachment CHECK (
        (attachment_key IS NULL AND attachment_name IS NULL AND attachment_format IS NULL AND attachment_mime IS NULL
            AND attachment_size IS NULL AND attachment_sha256 IS NULL)
     OR (attachment_key IS NOT NULL AND attachment_name IS NOT NULL AND attachment_mime IS NOT NULL
            AND attachment_format IN ('pdf', 'docx', 'pptx', 'xlsx', 'txt', 'jpg', 'png')
            AND attachment_size BETWEEN 1 AND 10485760 AND attachment_sha256 ~ '^[0-9a-f]{64}$')),
    CONSTRAINT fk_chat_message_conversation FOREIGN KEY (college_id, conversation_id)
        REFERENCES public.chat_conversations (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_chat_message_sender FOREIGN KEY (college_id, sender_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_chat_messages_conversation ON public.chat_messages (college_id, conversation_id, id DESC);

CREATE TABLE public.chat_blocks (
    college_id bigint NOT NULL,
    blocker_id bigint NOT NULL,
    blocked_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    PRIMARY KEY (blocker_id, blocked_id),
    CONSTRAINT ck_chat_block_self CHECK (blocker_id <> blocked_id),
    CONSTRAINT fk_chat_block_blocker FOREIGN KEY (college_id, blocker_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_chat_block_blocked FOREIGN KEY (college_id, blocked_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_chat_blocks_blocked ON public.chat_blocks (college_id, blocked_id);

CREATE TABLE public.chat_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    message_id bigint NOT NULL,
    reporter_id bigint NOT NULL,
    reason varchar(13) NOT NULL,
    note varchar(500),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_chat_report_once UNIQUE (message_id, reporter_id),
    CONSTRAINT ck_chat_report_reason CHECK (reason IN ('SPAM', 'ABUSE', 'HARASSMENT', 'INAPPROPRIATE', 'OTHER')),
    CONSTRAINT fk_chat_report_message FOREIGN KEY (college_id, message_id)
        REFERENCES public.chat_messages (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_chat_report_reporter FOREIGN KEY (college_id, reporter_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_chat_reports_reporter ON public.chat_reports (college_id, reporter_id);
