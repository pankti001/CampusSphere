-- Timetable management. Requires V9–V12 academic structure, V15's full-scope assignment key
-- (uq_attendance_assignment_scope) and V7's reject_privileged_audit_mutation().
-- Adds new tables only; no existing table or row is changed.
--
-- Versioning policy: each division + semester has a series of timetable versions. At most one DRAFT and one
-- PUBLISHED exist at a time. Entries can only change while their timetable is a DRAFT (enforced by trigger).
-- Changing a published timetable means starting a new draft version (a copy), editing it and publishing it;
-- publishing archives the previous version and records which version replaced it. Archived versions are kept.

CREATE TABLE public.classrooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL REFERENCES public.colleges (id) ON DELETE RESTRICT,
    code varchar(30) NOT NULL,
    name varchar(150) NOT NULL,
    capacity integer,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_classroom_college_id UNIQUE (college_id, id),
    CONSTRAINT uq_classroom_college_code UNIQUE (college_id, code),
    CONSTRAINT ck_classroom_code CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'),
    CONSTRAINT ck_classroom_name CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT ck_classroom_capacity CHECK (capacity IS NULL OR capacity BETWEEN 1 AND 2000)
);

CREATE TABLE public.timetables (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    department_id bigint NOT NULL,
    program_id bigint NOT NULL,
    academic_year_id bigint NOT NULL,
    semester_id bigint NOT NULL,
    division_id bigint NOT NULL,
    version integer NOT NULL,
    status varchar(9) NOT NULL DEFAULT 'DRAFT',
    revision bigint NOT NULL DEFAULT 0,
    created_by bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    published_by bigint,
    published_at timestamptz,
    archived_by bigint,
    archived_at timestamptz,
    replaced_by bigint,
    CONSTRAINT uq_timetable_college_id UNIQUE (college_id, id),
    CONSTRAINT uq_timetable_scope
        UNIQUE (college_id, id, department_id, program_id, academic_year_id, semester_id, division_id),
    CONSTRAINT uq_timetable_version UNIQUE (college_id, semester_id, division_id, version),
    CONSTRAINT fk_timetable_program FOREIGN KEY (college_id, department_id, program_id)
        REFERENCES public.academic_programs (college_id, department_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_semester FOREIGN KEY (college_id, program_id, academic_year_id, semester_id)
        REFERENCES public.academic_semesters (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_division FOREIGN KEY (college_id, program_id, academic_year_id, division_id)
        REFERENCES public.academic_divisions (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_creator FOREIGN KEY (college_id, created_by)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_publisher FOREIGN KEY (college_id, published_by)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_archiver FOREIGN KEY (college_id, archived_by)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_replacement FOREIGN KEY (college_id, replaced_by)
        REFERENCES public.timetables (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_timetable_version CHECK (version BETWEEN 1 AND 100000),
    CONSTRAINT ck_timetable_revision CHECK (revision >= 0),
    CONSTRAINT ck_timetable_state CHECK (
        (status = 'DRAFT' AND published_at IS NULL AND published_by IS NULL
            AND archived_at IS NULL AND archived_by IS NULL AND replaced_by IS NULL)
        OR (status = 'PUBLISHED' AND published_at IS NOT NULL AND published_by IS NOT NULL
            AND archived_at IS NULL AND archived_by IS NULL AND replaced_by IS NULL)
        OR (status = 'ARCHIVED' AND archived_at IS NOT NULL AND archived_by IS NOT NULL
            AND (published_at IS NULL) = (published_by IS NULL))),
    CONSTRAINT ck_timetable_times CHECK (
        updated_at >= created_at
        AND (published_at IS NULL OR published_at >= created_at)
        AND (archived_at IS NULL OR archived_at >= created_at)),
    CONSTRAINT ck_timetable_replacement CHECK (replaced_by IS NULL OR replaced_by <> id)
);

CREATE UNIQUE INDEX uq_timetable_one_draft ON public.timetables (college_id, semester_id, division_id)
    WHERE status = 'DRAFT';
CREATE UNIQUE INDEX uq_timetable_one_published ON public.timetables (college_id, semester_id, division_id)
    WHERE status = 'PUBLISHED';
CREATE INDEX ix_timetables_listing
    ON public.timetables (college_id, academic_year_id, program_id, semester_id, division_id, version DESC);
CREATE INDEX ix_timetables_status ON public.timetables (college_id, status, updated_at DESC);

CREATE TABLE public.timetable_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    timetable_id bigint NOT NULL,
    department_id bigint NOT NULL,
    program_id bigint NOT NULL,
    academic_year_id bigint NOT NULL,
    semester_id bigint NOT NULL,
    division_id bigint NOT NULL,
    kind varchar(6) NOT NULL,
    day_of_week smallint NOT NULL,
    start_time time(0) NOT NULL,
    end_time time(0) NOT NULL,
    assignment_id bigint,
    faculty_id bigint,
    subject_id bigint,
    classroom_id bigint,
    label varchar(60),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_by bigint NOT NULL,
    CONSTRAINT fk_timetable_entry_timetable
        FOREIGN KEY (college_id, timetable_id, department_id, program_id, academic_year_id, semester_id, division_id)
        REFERENCES public.timetables (college_id, id, department_id, program_id, academic_year_id, semester_id, division_id)
        ON DELETE RESTRICT,
    -- A lesson must use an assignment of this exact division and semester; faculty and subject come with it.
    CONSTRAINT fk_timetable_entry_assignment
        FOREIGN KEY (college_id, assignment_id, faculty_id, department_id, program_id, academic_year_id,
                     semester_id, division_id, subject_id)
        REFERENCES public.faculty_subject_assignments
            (college_id, id, faculty_id, department_id, program_id, academic_year_id, semester_id, division_id, subject_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_entry_classroom FOREIGN KEY (college_id, classroom_id)
        REFERENCES public.classrooms (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_entry_editor FOREIGN KEY (college_id, updated_by)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_timetable_entry_start UNIQUE (timetable_id, day_of_week, start_time),
    CONSTRAINT ck_timetable_entry_kind CHECK (kind IN ('LESSON', 'BREAK', 'LUNCH')),
    CONSTRAINT ck_timetable_entry_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_timetable_entry_time CHECK (end_time > start_time),
    CONSTRAINT ck_timetable_entry_label CHECK (label IS NULL OR label ~ '[^[:space:]]'),
    CONSTRAINT ck_timetable_entry_parts CHECK (
        (kind = 'LESSON' AND assignment_id IS NOT NULL AND faculty_id IS NOT NULL
            AND subject_id IS NOT NULL AND classroom_id IS NOT NULL)
        OR (kind IN ('BREAK', 'LUNCH') AND assignment_id IS NULL AND faculty_id IS NULL
            AND subject_id IS NULL AND classroom_id IS NULL)),
    CONSTRAINT ck_timetable_entry_times CHECK (updated_at >= created_at)
);

CREATE INDEX ix_timetable_entries_timetable
    ON public.timetable_entries (college_id, timetable_id, day_of_week, start_time);
CREATE INDEX ix_timetable_entries_faculty
    ON public.timetable_entries (college_id, faculty_id, day_of_week) WHERE faculty_id IS NOT NULL;
CREATE INDEX ix_timetable_entries_classroom
    ON public.timetable_entries (college_id, classroom_id, day_of_week) WHERE classroom_id IS NOT NULL;
CREATE INDEX ix_timetable_entries_assignment
    ON public.timetable_entries (college_id, assignment_id) WHERE assignment_id IS NOT NULL;
CREATE INDEX ix_timetable_entries_editor ON public.timetable_entries (college_id, updated_by);

CREATE FUNCTION public.require_draft_timetable() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
DECLARE
    target_college bigint;
    target_timetable bigint;
    parent_status varchar;
BEGIN
    IF TG_OP = 'DELETE' THEN
        target_college := OLD.college_id;
        target_timetable := OLD.timetable_id;
    ELSE
        target_college := NEW.college_id;
        target_timetable := NEW.timetable_id;
    END IF;
    IF TG_OP = 'UPDATE' AND (OLD.college_id <> NEW.college_id OR OLD.timetable_id <> NEW.timetable_id) THEN
        RAISE EXCEPTION 'Timetable entries cannot move between timetables' USING ERRCODE = '23514';
    END IF;
    SELECT t.status INTO parent_status FROM public.timetables t
    WHERE t.college_id = target_college AND t.id = target_timetable;
    IF parent_status IS DISTINCT FROM 'DRAFT' THEN
        RAISE EXCEPTION 'Only draft timetables can be changed' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER timetable_entries_draft_only
    BEFORE INSERT OR UPDATE OR DELETE ON public.timetable_entries
    FOR EACH ROW EXECUTE FUNCTION public.require_draft_timetable();

CREATE TABLE public.timetable_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    timetable_id bigint NOT NULL,
    actor_id bigint NOT NULL,
    action varchar(13) NOT NULL,
    entry_id bigint,
    detail varchar(300) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT fk_timetable_event_timetable FOREIGN KEY (college_id, timetable_id)
        REFERENCES public.timetables (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_timetable_event_actor FOREIGN KEY (college_id, actor_id)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_timetable_event_action CHECK (action IN
        ('CREATED', 'ENTRY_ADDED', 'ENTRY_CHANGED', 'ENTRY_REMOVED', 'PUBLISHED', 'REPLACED', 'ARCHIVED')),
    CONSTRAINT ck_timetable_event_detail CHECK (length(btrim(detail)) > 0)
);

CREATE INDEX ix_timetable_events_history ON public.timetable_events (college_id, timetable_id, id DESC);
CREATE INDEX ix_timetable_events_actor ON public.timetable_events (college_id, actor_id);
CREATE TRIGGER timetable_events_append_only
    BEFORE UPDATE OR DELETE OR TRUNCATE ON public.timetable_events
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();
