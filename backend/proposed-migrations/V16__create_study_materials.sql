ALTER TABLE public.faculty_subject_assignments ADD CONSTRAINT uq_material_assignment UNIQUE(college_id,id);
CREATE TABLE public.study_materials (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 college_id bigint NOT NULL, assignment_id bigint NOT NULL,
 title varchar(160) NOT NULL CHECK(length(btrim(title))>0),
 description varchar(2000) NOT NULL,
 kind varchar(16) NOT NULL CHECK(kind IN ('NOTES','READING','REFERENCE')),
 storage_key uuid NOT NULL UNIQUE, format varchar(3) NOT NULL CHECK(format IN ('pdf','txt')),
 byte_size integer NOT NULL CHECK(byte_size BETWEEN 1 AND 10485760),
 created_at timestamptz NOT NULL DEFAULT statement_timestamp(), archived_at timestamptz,
 UNIQUE(college_id,id),
 FOREIGN KEY(college_id,assignment_id) REFERENCES public.faculty_subject_assignments(college_id,id)
);
CREATE INDEX ix_material_active_class ON public.study_materials(college_id,assignment_id,id DESC) WHERE archived_at IS NULL;
CREATE TABLE public.study_material_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, college_id bigint NOT NULL,
 material_id bigint NOT NULL, actor_id bigint NOT NULL,
 action varchar(12) NOT NULL CHECK(action IN ('UPLOAD','EDIT','ARCHIVE')),
 occurred_at timestamptz NOT NULL DEFAULT statement_timestamp(),
 FOREIGN KEY(college_id,material_id) REFERENCES public.study_materials(college_id,id),
 FOREIGN KEY(college_id,actor_id) REFERENCES public.users(college_id,id)
);
CREATE INDEX ix_material_events ON public.study_material_events(college_id,material_id,id);
CREATE TRIGGER material_events_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON public.study_material_events
 FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();
