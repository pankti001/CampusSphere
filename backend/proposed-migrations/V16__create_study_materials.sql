-- V16: Study materials. Requires V1-V15 (faculty_subject_assignments from V12, student_enrollments from V13,
-- reject_privileged_audit_mutation() from V7). Stores metadata only; files live in private storage outside
-- the database and are addressed by a random storage key. Creates no rows.

ALTER TABLE public.faculty_subject_assignments
    ADD CONSTRAINT uq_material_assignment_scope UNIQUE (college_id, id, faculty_id, division_id, subject_id);

CREATE TABLE public.study_materials (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    assignment_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    division_id bigint NOT NULL,
    subject_id bigint NOT NULL,
    title varchar(160) NOT NULL CHECK (length(btrim(title)) > 0),
    description varchar(2000) NOT NULL DEFAULT '',
    topic varchar(120) CHECK (topic IS NULL OR length(btrim(topic)) > 0),
    material_type varchar(16) NOT NULL
        CHECK (material_type IN ('NOTES', 'SLIDES', 'ASSIGNMENT', 'QUESTION_BANK', 'LAB_MANUAL', 'REFERENCE', 'OTHER')),
    original_filename varchar(200) NOT NULL CHECK (length(btrim(original_filename)) > 0),
    storage_key uuid NOT NULL UNIQUE,
    file_format varchar(4) NOT NULL CHECK (file_format IN ('pdf', 'docx', 'pptx', 'xlsx', 'txt')),
    mime_type varchar(100) NOT NULL,
    byte_size integer NOT NULL CHECK (byte_size BETWEEN 1 AND 10485760),
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    status varchar(10) NOT NULL DEFAULT 'PUBLISHED' CHECK (status IN ('PUBLISHED', 'HIDDEN', 'REMOVED', 'DELETED')),
    moderation_note varchar(500),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT ck_study_material_times CHECK (updated_at >= created_at),
    CONSTRAINT ck_study_material_moderation_note CHECK (status NOT IN ('HIDDEN', 'REMOVED') OR moderation_note IS NOT NULL),
    CONSTRAINT uq_study_material_college_id UNIQUE (college_id, id),
    CONSTRAINT fk_study_material_assignment
        FOREIGN KEY (college_id, assignment_id, faculty_id, division_id, subject_id)
        REFERENCES public.faculty_subject_assignments (college_id, id, faculty_id, division_id, subject_id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_study_material_active_file
    ON public.study_materials (college_id, assignment_id, sha256) WHERE status IN ('PUBLISHED', 'HIDDEN');
CREATE INDEX ix_study_materials_class
    ON public.study_materials (college_id, division_id, subject_id, id DESC) WHERE status = 'PUBLISHED';
CREATE INDEX ix_study_materials_faculty ON public.study_materials (college_id, faculty_id, id DESC);
CREATE INDEX ix_study_materials_college ON public.study_materials (college_id, status, id DESC);

CREATE TABLE public.study_material_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    material_id bigint NOT NULL,
    actor_id bigint NOT NULL,
    action varchar(8) NOT NULL CHECK (action IN ('UPLOAD', 'EDIT', 'DELETE', 'HIDE', 'RESTORE', 'REMOVE')),
    note varchar(500),
    occurred_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT fk_study_material_event_material FOREIGN KEY (college_id, material_id)
        REFERENCES public.study_materials (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_study_material_event_actor FOREIGN KEY (college_id, actor_id)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT
);
CREATE INDEX ix_study_material_events ON public.study_material_events (college_id, material_id, id);
CREATE TRIGGER study_material_events_append_only
    BEFORE UPDATE OR DELETE OR TRUNCATE ON public.study_material_events
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();
