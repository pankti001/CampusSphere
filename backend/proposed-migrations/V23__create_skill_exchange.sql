-- PROPOSED, NOT APPLIED. Needs the project owner's approval before it is run on any database.
--
-- Skill Exchange, strictly inside one college. Requires V13 (student_profiles). Adds six tables and two trigger
-- functions; no existing table, column or row is changed.
--
--   skill_offers          a skill a student offers to teach (name, category, level, method, mode, status)
--   skill_offer_slots     the days and times an offer is available
--   skill_requests        a request to learn an offer; a mutual exchange also names the learner's own offer
--   skill_sessions        a learning session for an accepted request (requested -> scheduled -> completed/cancelled)
--   skill_reviews         one rating and comment per person per completed session
--   skill_notifications   in-app notices; a unique event key makes retries and repeated reminders insert nothing twice
--
-- College isolation is enforced by the database as well as the application: every relationship carries college_id
-- inside its foreign key, so an offer, request, session, review or notice can only ever join rows of its own
-- college, even if application code were wrong. There is no cross-college table or view.

CREATE TABLE public.skill_offers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    student_id bigint NOT NULL,
    name varchar(60) NOT NULL,
    category varchar(12) NOT NULL,
    description varchar(1000) NOT NULL DEFAULT '',
    level varchar(12) NOT NULL,
    teaching_method varchar(300) NOT NULL DEFAULT '',
    mode varchar(9) NOT NULL,
    status varchar(8) NOT NULL DEFAULT 'ACTIVE',
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_skill_offer_college_id UNIQUE (college_id, id),
    CONSTRAINT uq_skill_offer_owner UNIQUE (college_id, id, student_id),
    CONSTRAINT ck_skill_offer_name CHECK (length(btrim(name)) >= 2),
    CONSTRAINT ck_skill_offer_category CHECK (category IN ('PROGRAMMING', 'DESIGN', 'LANGUAGES', 'MATHEMATICS',
        'SCIENCE', 'BUSINESS', 'ARTS', 'MUSIC', 'SPORTS', 'ACADEMICS', 'OTHER')),
    CONSTRAINT ck_skill_offer_level CHECK (level IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')),
    CONSTRAINT ck_skill_offer_mode CHECK (mode IN ('ONLINE', 'IN_PERSON', 'BOTH')),
    CONSTRAINT ck_skill_offer_status CHECK (status IN ('ACTIVE', 'PAUSED', 'ARCHIVED')),
    CONSTRAINT ck_skill_offer_times CHECK (updated_at >= created_at),
    CONSTRAINT fk_skill_offer_student FOREIGN KEY (college_id, student_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
-- One live offer per skill name per student.
CREATE UNIQUE INDEX uq_skill_offer_name ON public.skill_offers (college_id, student_id, lower(name)) WHERE status <> 'ARCHIVED';
CREATE INDEX ix_skill_offers_market ON public.skill_offers (college_id, status, category, updated_at DESC);

CREATE TABLE public.skill_offer_slots (
    college_id bigint NOT NULL,
    offer_id bigint NOT NULL,
    day_of_week smallint NOT NULL,
    start_time time(0) NOT NULL,
    end_time time(0) NOT NULL,
    PRIMARY KEY (offer_id, day_of_week, start_time),
    CONSTRAINT ck_skill_slot_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_skill_slot_time CHECK (end_time > start_time),
    CONSTRAINT fk_skill_slot_offer FOREIGN KEY (college_id, offer_id)
        REFERENCES public.skill_offers (college_id, id) ON DELETE CASCADE
);

CREATE TABLE public.skill_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    offer_id bigint NOT NULL,
    provider_id bigint NOT NULL,
    learner_id bigint NOT NULL,
    exchange_offer_id bigint,
    message varchar(500) NOT NULL DEFAULT '',
    status varchar(9) NOT NULL DEFAULT 'REQUESTED',
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    decided_at timestamptz,
    cancelled_by bigint,
    CONSTRAINT uq_skill_request_college_id UNIQUE (college_id, id),
    CONSTRAINT uq_skill_request_partners UNIQUE (college_id, id, provider_id, learner_id),
    CONSTRAINT ck_skill_request_self CHECK (provider_id <> learner_id),
    CONSTRAINT ck_skill_request_status CHECK (status IN ('REQUESTED', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT ck_skill_request_decided CHECK ((status = 'REQUESTED') = (decided_at IS NULL)),
    CONSTRAINT ck_skill_request_cancelled CHECK ((status = 'CANCELLED') = (cancelled_by IS NOT NULL)
        AND (cancelled_by IS NULL OR cancelled_by IN (provider_id, learner_id))),
    CONSTRAINT ck_skill_request_time CHECK (decided_at IS NULL OR decided_at >= created_at),
    -- The offer belongs to the provider, the exchange offer to the learner, all in this college.
    CONSTRAINT fk_skill_request_offer FOREIGN KEY (college_id, offer_id, provider_id)
        REFERENCES public.skill_offers (college_id, id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_request_exchange FOREIGN KEY (college_id, exchange_offer_id, learner_id)
        REFERENCES public.skill_offers (college_id, id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_request_learner FOREIGN KEY (college_id, learner_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
-- One open request per learner per offer.
CREATE UNIQUE INDEX uq_skill_request_open ON public.skill_requests (offer_id, learner_id) WHERE status IN ('REQUESTED', 'ACCEPTED');
CREATE INDEX ix_skill_requests_provider ON public.skill_requests (college_id, provider_id, status, id DESC);
CREATE INDEX ix_skill_requests_learner ON public.skill_requests (college_id, learner_id, status, id DESC);

CREATE TABLE public.skill_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    request_id bigint NOT NULL,
    provider_id bigint NOT NULL,
    learner_id bigint NOT NULL,
    offer_id bigint NOT NULL,
    teacher_id bigint NOT NULL,
    pupil_id bigint NOT NULL,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    mode varchar(9) NOT NULL,
    place varchar(300) NOT NULL DEFAULT '',
    status varchar(9) NOT NULL DEFAULT 'REQUESTED',
    proposed_by bigint NOT NULL,
    confirmed_at timestamptz,
    cancelled_by bigint,
    cancel_reason varchar(300),
    completed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_skill_session_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_skill_session_people CHECK ((teacher_id = provider_id AND pupil_id = learner_id)
        OR (teacher_id = learner_id AND pupil_id = provider_id)),
    CONSTRAINT ck_skill_session_proposer CHECK (proposed_by IN (provider_id, learner_id)),
    CONSTRAINT ck_skill_session_time CHECK (ends_at > starts_at AND ends_at <= starts_at + interval '4 hours'),
    CONSTRAINT ck_skill_session_mode CHECK (mode IN ('ONLINE', 'IN_PERSON')),
    CONSTRAINT ck_skill_session_status CHECK (status IN ('REQUESTED', 'SCHEDULED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_skill_session_shape CHECK (
        (status = 'REQUESTED' AND confirmed_at IS NULL AND cancelled_by IS NULL AND completed_at IS NULL)
     OR (status = 'SCHEDULED' AND confirmed_at IS NOT NULL AND cancelled_by IS NULL AND completed_at IS NULL)
     OR (status = 'COMPLETED' AND confirmed_at IS NOT NULL AND cancelled_by IS NULL AND completed_at IS NOT NULL)
     OR (status = 'CANCELLED' AND cancelled_by IN (provider_id, learner_id) AND completed_at IS NULL)),
    -- The session belongs to a request between exactly these two students of this college,
    -- and the skill taught is the teacher's own offer.
    CONSTRAINT fk_skill_session_request FOREIGN KEY (college_id, request_id, provider_id, learner_id)
        REFERENCES public.skill_requests (college_id, id, provider_id, learner_id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_session_offer FOREIGN KEY (college_id, offer_id, teacher_id)
        REFERENCES public.skill_offers (college_id, id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_skill_sessions_teacher ON public.skill_sessions (college_id, teacher_id, starts_at);
CREATE INDEX ix_skill_sessions_pupil ON public.skill_sessions (college_id, pupil_id, starts_at);
CREATE INDEX ix_skill_sessions_request ON public.skill_sessions (college_id, request_id);
CREATE INDEX ix_skill_sessions_upcoming ON public.skill_sessions (starts_at) WHERE status = 'SCHEDULED';

CREATE TABLE public.skill_reviews (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    session_id bigint NOT NULL,
    reviewer_id bigint NOT NULL,
    reviewee_id bigint NOT NULL,
    rating smallint NOT NULL,
    comment varchar(1000) NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_skill_review_once UNIQUE (session_id, reviewer_id),
    CONSTRAINT ck_skill_review_self CHECK (reviewer_id <> reviewee_id),
    CONSTRAINT ck_skill_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT fk_skill_review_session FOREIGN KEY (college_id, session_id)
        REFERENCES public.skill_sessions (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_review_reviewer FOREIGN KEY (college_id, reviewer_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_review_reviewee FOREIGN KEY (college_id, reviewee_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT
);
CREATE INDEX ix_skill_reviews_reviewee ON public.skill_reviews (college_id, reviewee_id, id DESC);

-- A review is only for a completed session, written by one of its two students about the other.
CREATE FUNCTION public.check_skill_review() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM public.skill_sessions s
                   WHERE s.college_id = NEW.college_id AND s.id = NEW.session_id AND s.status = 'COMPLETED'
                     AND ((s.teacher_id = NEW.reviewer_id AND s.pupil_id = NEW.reviewee_id)
                       OR (s.pupil_id = NEW.reviewer_id AND s.teacher_id = NEW.reviewee_id))) THEN
        RAISE EXCEPTION 'Only the two students of a completed session can review each other' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER skill_review_participants
    BEFORE INSERT OR UPDATE ON public.skill_reviews
    FOR EACH ROW EXECUTE FUNCTION public.check_skill_review();

CREATE TABLE public.skill_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    student_id bigint NOT NULL,
    kind varchar(18) NOT NULL,
    event_key varchar(100) NOT NULL,
    title varchar(200) NOT NULL,
    body varchar(600) NOT NULL,
    request_id bigint,
    session_id bigint,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    read_at timestamptz,
    CONSTRAINT uq_skill_notification_event UNIQUE (college_id, student_id, event_key),
    CONSTRAINT ck_skill_notification_kind CHECK (kind IN ('REQUEST_NEW', 'REQUEST_ACCEPTED', 'REQUEST_REJECTED',
        'REQUEST_CANCELLED', 'SESSION_PROPOSED', 'SESSION_SCHEDULED', 'SESSION_CANCELLED', 'SESSION_REMINDER', 'REVIEW_NEW')),
    CONSTRAINT ck_skill_notification_text CHECK (title ~ '[^[:space:]]' AND body ~ '[^[:space:]]'),
    CONSTRAINT ck_skill_notification_read CHECK (read_at IS NULL OR read_at >= created_at),
    CONSTRAINT fk_skill_notification_student FOREIGN KEY (college_id, student_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_notification_request FOREIGN KEY (college_id, request_id)
        REFERENCES public.skill_requests (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_skill_notification_session FOREIGN KEY (college_id, session_id)
        REFERENCES public.skill_sessions (college_id, id) ON DELETE RESTRICT
);
CREATE INDEX ix_skill_notifications_inbox ON public.skill_notifications (college_id, student_id, id DESC);
CREATE INDEX ix_skill_notifications_unread ON public.skill_notifications (college_id, student_id) WHERE read_at IS NULL;

-- Notifications are history: only an unread notification may be marked read, and rows cannot be deleted.
CREATE FUNCTION public.protect_skill_notification() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Skill notifications are kept as history' USING ERRCODE = '42501';
    END IF;
    IF (NEW.id, NEW.college_id, NEW.student_id, NEW.kind, NEW.event_key, NEW.title, NEW.body, NEW.request_id,
        NEW.session_id, NEW.created_at)
       IS DISTINCT FROM
       (OLD.id, OLD.college_id, OLD.student_id, OLD.kind, OLD.event_key, OLD.title, OLD.body, OLD.request_id,
        OLD.session_id, OLD.created_at)
       OR (OLD.read_at IS NOT NULL AND NEW.read_at IS DISTINCT FROM OLD.read_at) THEN
        RAISE EXCEPTION 'Only an unread notification can be marked as read' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER skill_notifications_history
    BEFORE UPDATE OR DELETE ON public.skill_notifications
    FOR EACH ROW EXECUTE FUNCTION public.protect_skill_notification();
CREATE TRIGGER skill_notifications_no_truncate
    BEFORE TRUNCATE ON public.skill_notifications
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();
