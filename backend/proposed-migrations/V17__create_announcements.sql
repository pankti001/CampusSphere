-- V17: College announcements. Requires V1-V16 (users/departments from V1-V5, academic catalogue V9-V11,
-- faculty assignments V12, student enrollments V13). Additive only: creates two tables, no rows, no changes
-- to existing tables.
--
-- Time policy: publish_at and expires_at are absolute instants (timestamptz, stored in UTC). Visibility is
-- always decided by the database clock (statement_timestamp()). SCHEDULED and EXPIRED are not stored; they
-- are derived from status = 'PUBLISHED' plus those two instants, so no background job is needed.

CREATE TABLE public.announcements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    author_id bigint NOT NULL,
    author_role varchar(13) NOT NULL CHECK (author_role IN ('COLLEGE_ADMIN', 'FACULTY')),
    title varchar(200) NOT NULL CHECK (length(btrim(title)) > 0),
    body varchar(10000) NOT NULL CHECK (length(btrim(body)) > 0),
    category varchar(16) NOT NULL CHECK (category IN ('GENERAL', 'ACADEMIC', 'EXAMINATION', 'EVENTS', 'HOLIDAYS',
        'FEES', 'IMPORTANT_NOTICE', 'EMERGENCY')),
    priority varchar(6) NOT NULL CHECK (priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')),
    audience varchar(8) NOT NULL CHECK (audience IN ('EVERYONE', 'STUDENTS', 'FACULTY')),
    scope varchar(13) NOT NULL CHECK (scope IN ('COLLEGE', 'DEPARTMENT', 'PROGRAM', 'ACADEMIC_YEAR', 'SEMESTER', 'DIVISION')),
    department_id bigint,
    program_id bigint,
    academic_year_id bigint,
    semester_id bigint,
    division_id bigint,
    status varchar(9) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    publish_at timestamptz,
    expires_at timestamptz,
    attachment_name varchar(200),
    attachment_key uuid UNIQUE,
    attachment_format varchar(4) CHECK (attachment_format IN ('pdf', 'docx', 'pptx', 'xlsx', 'txt')),
    attachment_mime varchar(100),
    attachment_size integer CHECK (attachment_size BETWEEN 1 AND 10485760),
    attachment_sha256 char(64) CHECK (attachment_sha256 ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_by bigint NOT NULL,
    CONSTRAINT uq_announcement_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_announcement_times CHECK (updated_at >= created_at),
    CONSTRAINT ck_announcement_published_time CHECK (status <> 'PUBLISHED' OR publish_at IS NOT NULL),
    CONSTRAINT ck_announcement_expiry CHECK (expires_at IS NULL OR publish_at IS NULL OR expires_at > publish_at),
    -- Exactly the identifiers that belong to the chosen scope are present.
    CONSTRAINT ck_announcement_scope CHECK (
        (scope = 'COLLEGE' AND department_id IS NULL AND program_id IS NULL AND academic_year_id IS NULL
            AND semester_id IS NULL AND division_id IS NULL)
     OR (scope = 'DEPARTMENT' AND department_id IS NOT NULL AND program_id IS NULL AND academic_year_id IS NULL
            AND semester_id IS NULL AND division_id IS NULL)
     OR (scope = 'PROGRAM' AND department_id IS NOT NULL AND program_id IS NOT NULL AND academic_year_id IS NULL
            AND semester_id IS NULL AND division_id IS NULL)
     OR (scope = 'ACADEMIC_YEAR' AND department_id IS NULL AND program_id IS NULL AND academic_year_id IS NOT NULL
            AND semester_id IS NULL AND division_id IS NULL)
     OR (scope = 'SEMESTER' AND department_id IS NOT NULL AND program_id IS NOT NULL AND academic_year_id IS NOT NULL
            AND semester_id IS NOT NULL AND division_id IS NULL)
     OR (scope = 'DIVISION' AND department_id IS NOT NULL AND program_id IS NOT NULL AND academic_year_id IS NOT NULL
            AND semester_id IS NULL AND division_id IS NOT NULL)),
    -- Attachment metadata is all present or all absent.
    CONSTRAINT ck_announcement_attachment CHECK (
        (attachment_key IS NULL AND attachment_name IS NULL AND attachment_format IS NULL AND attachment_mime IS NULL
            AND attachment_size IS NULL AND attachment_sha256 IS NULL)
     OR (attachment_key IS NOT NULL AND attachment_name IS NOT NULL AND attachment_format IS NOT NULL
            AND attachment_mime IS NOT NULL AND attachment_size IS NOT NULL AND attachment_sha256 IS NOT NULL)),
    -- Tenant-matched references: an announcement can only point at its own college's records.
    CONSTRAINT fk_announcement_author FOREIGN KEY (college_id, author_id)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_announcement_updater FOREIGN KEY (college_id, updated_by)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_announcement_department FOREIGN KEY (college_id, department_id)
        REFERENCES public.departments (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_announcement_program FOREIGN KEY (college_id, department_id, program_id)
        REFERENCES public.academic_programs (college_id, department_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_announcement_year FOREIGN KEY (college_id, academic_year_id)
        REFERENCES public.academic_years (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_announcement_semester FOREIGN KEY (college_id, program_id, academic_year_id, semester_id)
        REFERENCES public.academic_semesters (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_announcement_division FOREIGN KEY (college_id, program_id, academic_year_id, division_id)
        REFERENCES public.academic_divisions (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT
);
CREATE INDEX ix_announcements_feed ON public.announcements (college_id, status, publish_at DESC, id DESC);
CREATE INDEX ix_announcements_author ON public.announcements (college_id, author_id, id DESC);

CREATE TABLE public.announcement_reads (
    college_id bigint NOT NULL,
    announcement_id bigint NOT NULL,
    user_id bigint NOT NULL,
    read_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    PRIMARY KEY (announcement_id, user_id),
    CONSTRAINT fk_announcement_read_announcement FOREIGN KEY (college_id, announcement_id)
        REFERENCES public.announcements (college_id, id) ON DELETE CASCADE,
    CONSTRAINT fk_announcement_read_user FOREIGN KEY (college_id, user_id)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT
);
CREATE INDEX ix_announcement_reads_user ON public.announcement_reads (college_id, user_id);
