ALTER TABLE public.faculty_subject_assignments ADD CONSTRAINT uq_attendance_assignment_scope
    UNIQUE (college_id, id, faculty_id, department_id, program_id, academic_year_id, semester_id, division_id, subject_id);

ALTER TABLE public.student_enrollments ADD CONSTRAINT uq_attendance_enrollment_scope
    UNIQUE (college_id, id, student_id, department_id, program_id, academic_year_id, semester_id, division_id);

CREATE TABLE public.attendance_policies (
    college_id bigint PRIMARY KEY REFERENCES public.colleges(id) ON DELETE RESTRICT,
    warning_threshold numeric(5,2) NOT NULL DEFAULT 75,
    critical_threshold numeric(5,2) NOT NULL DEFAULT 65,
    count_late boolean NOT NULL DEFAULT true,
    exclude_excused boolean NOT NULL DEFAULT true,
    correction_hours smallint NOT NULL DEFAULT 48 CHECK (correction_hours BETWEEN 0 AND 720),
    CHECK (critical_threshold >= 0 AND critical_threshold < warning_threshold AND warning_threshold <= 100)
);

CREATE TABLE public.attendance_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    assignment_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    department_id bigint NOT NULL,
    program_id bigint NOT NULL,
    academic_year_id bigint NOT NULL,
    semester_id bigint NOT NULL,
    division_id bigint NOT NULL,
    subject_id bigint NOT NULL,
    session_date date NOT NULL,
    lecture_number smallint NOT NULL CHECK (lecture_number BETWEEN 1 AND 99),
    start_time time,
    end_time time,
    roster_at timestamptz NOT NULL,
    status varchar(9) NOT NULL DEFAULT 'DRAFT',
    revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    submitted_at timestamptz,
    locked_at timestamptz,
    CONSTRAINT fk_attendance_assignment_scope
        FOREIGN KEY (college_id, assignment_id, faculty_id, department_id, program_id, academic_year_id,
                     semester_id, division_id, subject_id)
        REFERENCES public.faculty_subject_assignments
            (college_id,id,faculty_id,department_id,program_id,academic_year_id,semester_id,division_id,subject_id)
        ON DELETE RESTRICT,
    CONSTRAINT uq_attendance_lecture UNIQUE (college_id, subject_id, division_id, session_date, lecture_number),
    CONSTRAINT uq_attendance_session_scope
        UNIQUE (college_id, id, department_id, program_id, academic_year_id, semester_id, division_id),
    CHECK (end_time IS NULL OR (start_time IS NOT NULL AND end_time > start_time)),
    CHECK (roster_at <= created_at),
    CHECK (
        (status = 'DRAFT' AND submitted_at IS NULL AND locked_at IS NULL)
        OR (status = 'SUBMITTED' AND submitted_at IS NOT NULL AND submitted_at >= created_at AND locked_at IS NULL)
        OR (status = 'LOCKED' AND submitted_at IS NOT NULL AND submitted_at >= created_at
            AND locked_at IS NOT NULL AND locked_at >= submitted_at)
    )
);

CREATE INDEX ix_attendance_faculty_history ON public.attendance_sessions
    (college_id, faculty_id, session_date DESC, id DESC);
CREATE INDEX ix_attendance_college_reports ON public.attendance_sessions
    (college_id, session_date DESC, id DESC) WHERE status IN ('SUBMITTED','LOCKED');

CREATE TABLE public.attendance_records (
    college_id bigint NOT NULL,
    session_id bigint NOT NULL,
    student_id bigint NOT NULL,
    enrollment_id bigint NOT NULL,
    department_id bigint NOT NULL,
    program_id bigint NOT NULL,
    academic_year_id bigint NOT NULL,
    semester_id bigint NOT NULL,
    division_id bigint NOT NULL,
    status varchar(7) CHECK (status IN ('PRESENT', 'ABSENT', 'LATE', 'EXCUSED')),
    PRIMARY KEY (college_id, session_id, student_id),
    FOREIGN KEY (college_id, session_id, department_id, program_id, academic_year_id, semester_id, division_id)
        REFERENCES public.attendance_sessions
            (college_id, id, department_id, program_id, academic_year_id, semester_id, division_id) ON DELETE RESTRICT,
    FOREIGN KEY (college_id, enrollment_id, student_id, department_id, program_id, academic_year_id, semester_id, division_id)
        REFERENCES public.student_enrollments
            (college_id, id, student_id, department_id, program_id, academic_year_id, semester_id, division_id) ON DELETE RESTRICT
);

CREATE INDEX ix_attendance_student_history ON public.attendance_records (college_id, student_id, session_id);
CREATE INDEX ix_attendance_student_enrollment ON public.attendance_records (college_id, enrollment_id);

CREATE FUNCTION public.check_published_attendance_roster() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    IF NEW.status IN ('SUBMITTED', 'LOCKED') AND (
        NOT EXISTS (SELECT FROM public.attendance_records r WHERE r.college_id = NEW.college_id AND r.session_id = NEW.id)
        OR EXISTS (SELECT FROM public.attendance_records r
                   WHERE r.college_id = NEW.college_id AND r.session_id = NEW.id AND r.status IS NULL)
    ) THEN
        RAISE EXCEPTION 'Published attendance requires a fully marked roster' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER attendance_require_published_roster
    BEFORE INSERT OR UPDATE OF status ON public.attendance_sessions
    FOR EACH ROW EXECUTE FUNCTION public.check_published_attendance_roster();

CREATE TABLE public.attendance_corrections (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    session_id bigint NOT NULL,
    student_id bigint NOT NULL,
    actor_id bigint NOT NULL,
    previous_status varchar(7) NOT NULL CHECK (previous_status IN ('PRESENT', 'ABSENT', 'LATE', 'EXCUSED')),
    new_status varchar(7) NOT NULL CHECK (new_status IN ('PRESENT', 'ABSENT', 'LATE', 'EXCUSED')),
    reason varchar(500) NOT NULL CHECK (length(btrim(reason)) > 0),
    corrected_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CHECK (previous_status <> new_status),
    FOREIGN KEY (college_id, session_id, student_id)
        REFERENCES public.attendance_records (college_id, session_id, student_id) ON DELETE RESTRICT,
    FOREIGN KEY (college_id, actor_id) REFERENCES public.users (college_id, id) ON DELETE RESTRICT
);

CREATE INDEX ix_attendance_correction_history ON public.attendance_corrections (college_id, session_id, id);
CREATE INDEX ix_attendance_correction_actor ON public.attendance_corrections (college_id, actor_id);
CREATE TRIGGER attendance_corrections_append_only
    BEFORE UPDATE OR DELETE OR TRUNCATE ON public.attendance_corrections
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();

CREATE TABLE public.attendance_alerts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    student_id bigint NOT NULL,
    severity varchar(8) NOT NULL CHECK (severity IN ('WARNING', 'CRITICAL')),
    percentage numeric(5,2) NOT NULL CHECK (percentage BETWEEN 0 AND 100),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    resolved_at timestamptz CHECK (resolved_at IS NULL OR resolved_at >= created_at),
    FOREIGN KEY (college_id, student_id) REFERENCES public.users (college_id, id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_attendance_open_alert ON public.attendance_alerts (college_id, student_id)
    WHERE resolved_at IS NULL;
CREATE INDEX ix_attendance_alert_history ON public.attendance_alerts (college_id, student_id, id DESC);
CREATE INDEX ix_attendance_college_alerts ON public.attendance_alerts (college_id, id DESC) WHERE resolved_at IS NULL;
