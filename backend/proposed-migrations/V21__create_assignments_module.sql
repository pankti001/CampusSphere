CREATE INDEX ix_assignment_notifications_inbox ON public.assignment_notifications (college_id, student_id, id DESC);
CREATE INDEX ix_assignment_notifications_unread ON public.assignment_notifications (college_id, student_id)
    WHERE read_at IS NULL;
CREATE INDEX ix_assignment_notifications_assignment ON public.assignment_notifications (college_id, assignment_id);

-- Notifications are history: only an unread notification may be marked read, and rows cannot be deleted.
CREATE FUNCTION public.protect_assignment_notification() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Assignment notifications are kept as history' USING ERRCODE = '42501';
    END IF;
    IF (NEW.id, NEW.college_id, NEW.student_id, NEW.assignment_id, NEW.submission_id, NEW.event_key, NEW.kind,
        NEW.title, NEW.body, NEW.created_at)
       IS DISTINCT FROM
       (OLD.id, OLD.college_id, OLD.student_id, OLD.assignment_id, OLD.submission_id, OLD.event_key, OLD.kind,
        OLD.title, OLD.body, OLD.created_at)
       OR (OLD.read_at IS NOT NULL AND NEW.read_at IS DISTINCT FROM OLD.read_at) THEN
        RAISE EXCEPTION 'Only an unread notification can be marked as read' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER assignment_notifications_history
    BEFORE UPDATE OR DELETE ON public.assignment_notifications
    FOR EACH ROW EXECUTE FUNCTION public.protect_assignment_notification();
CREATE TRIGGER assignment_notifications_no_truncate
    BEFORE TRUNCATE ON public.assignment_notifications
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();
