    CONSTRAINT uq_assignment_notification_event UNIQUE (college_id, student_id, event_key),
    CONSTRAINT ck_assignment_notification_kind CHECK (kind IN ('PUBLISHED', 'DEADLINE_CHANGED', 'EVALUATED', 'RETURNED')),
    CONSTRAINT ck_assignment_notification_text CHECK (title ~ '[^[:space:]]' AND body ~ '[^[:space:]]'),
