-- PROPOSED, NOT APPLIED. Needs the project owner's approval before it is run on any database.
--
-- Assignments and homework. Requires V12 (faculty_subject_assignments, faculty_profiles), V13 (student_profiles,
-- student_enrollments), V16 (uq_material_assignment_scope) and V7 (reject_privileged_audit_mutation).
-- Adds four tables and two trigger functions. No existing table, column or row is changed.
--
--   assignments                 one piece of work set by a faculty member for one of their classes
--   assignment_submissions      every attempt a student uploads; earlier attempts are kept, never overwritten
--   assignment_events           append-only history (create, publish, deadline change, submit, evaluate, ...)
--   assignment_notifications    in-app notices to students; unique event keys make retries insert nothing twice
--
-- An assignment points at the faculty_subject_assignments row (the "teaching assignment") it was created from,
-- so program, academic year, semester, division and subject always come from real records in the same college.

CREATE TABLE public.assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    teaching_assignment_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    division_id bigint NOT NULL,
    subject_id bigint NOT NULL,
    title varchar(160) NOT NULL,
    description varchar(4000) NOT NULL DEFAULT '',
    instructions varchar(4000) NOT NULL DEFAULT '',
    issue_at timestamptz NOT NULL,
    due_at timestamptz NOT NULL,
    max_marks numeric(6,2) NOT NULL,
    allowed_formats varchar(4)[] NOT NULL,
    max_file_bytes integer NOT NULL DEFAULT 10485760,
    late_policy varchar(7) NOT NULL DEFAULT 'NONE',
    late_until timestamptz,
    resubmission varchar(14) NOT NULL DEFAULT 'SINGLE',
    status varchar(9) NOT NULL DEFAULT 'DRAFT',
    published_at timestamptz,
    closed_at timestamptz,
    archived_at timestamptz,
    attachment_name varchar(200),
    attachment_key uuid UNIQUE,
    attachment_format varchar(4),
    attachment_mime varchar(100),
    attachment_size integer,
    attachment_sha256 char(64),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_assignment_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_assignment_title CHECK (title ~ '[^[:space:]]'),
    CONSTRAINT ck_assignment_dates CHECK (due_at > issue_at),
    CONSTRAINT ck_assignment_marks CHECK (max_marks > 0 AND max_marks <= 1000),
    CONSTRAINT ck_assignment_formats CHECK (cardinality(allowed_formats) BETWEEN 1 AND 7
        AND allowed_formats <@ ARRAY['pdf', 'docx', 'pptx', 'xlsx', 'txt', 'jpg', 'png']::varchar(4)[]),
    CONSTRAINT ck_assignment_file_size CHECK (max_file_bytes BETWEEN 102400 AND 10485760),
    CONSTRAINT ck_assignment_late CHECK (
        (late_policy = 'NONE' AND late_until IS NULL)
     OR (late_policy = 'ALLOWED' AND late_until IS NOT NULL AND late_until > due_at)),
    CONSTRAINT ck_assignment_resubmission CHECK (resubmission IN ('SINGLE', 'UNTIL_DEADLINE')),
    CONSTRAINT ck_assignment_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED', 'ARCHIVED')),
    CONSTRAINT ck_assignment_lifecycle CHECK (
        (status = 'DRAFT' OR archived_at IS NOT NULL OR published_at IS NOT NULL)
        AND (status <> 'PUBLISHED' OR published_at IS NOT NULL)
        AND (status <> 'CLOSED' OR closed_at IS NOT NULL)
        AND (status <> 'ARCHIVED' OR archived_at IS NOT NULL)),
    CONSTRAINT ck_assignment_times CHECK (updated_at >= created_at),
    CONSTRAINT ck_assignment_attachment CHECK (
        (attachment_key IS NULL AND attachment_name IS NULL AND attachment_format IS NULL AND attachment_mime IS NULL
            AND attachment_size IS NULL AND attachment_sha256 IS NULL)
     OR (attachment_key IS NOT NULL AND attachment_name IS NOT NULL AND attachment_mime IS NOT NULL
            AND attachment_format IN ('pdf', 'docx', 'pptx', 'xlsx', 'txt', 'jpg', 'png')
            AND attachment_size BETWEEN 1 AND 10485760 AND attachment_sha256 ~ '^[0-9a-f]{64}$')),
    -- The teaching assignment must belong to this college, this faculty member, this division and this subject.
    CONSTRAINT fk_assignment_teaching
        FOREIGN KEY (college_id, teaching_assignment_id, faculty_id, division_id, subject_id)
        REFERENCES public.faculty_subject_assignments (college_id, id, faculty_id, division_id, subject_id)
        ON DELETE RESTRICT
);
CREATE INDEX ix_assignments_class ON public.assignments (college_id, division_id, subject_id, status, due_at);
CREATE INDEX ix_assignments_faculty ON public.assignments (college_id, faculty_id, id DESC);
CREATE INDEX ix_assignments_teaching ON public.assignments (college_id, teaching_assignment_id);
CREATE INDEX ix_assignments_college ON public.assignments (college_id, status, due_at DESC);

CREATE TABLE public.assignment_submissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    assignment_id bigint NOT NULL,
    student_id bigint NOT NULL,
    attempt smallint NOT NULL,
    original_filename varchar(200) NOT NULL,
    storage_key uuid NOT NULL UNIQUE,
    file_format varchar(4) NOT NULL,
    mime_type varchar(100) NOT NULL,
    byte_size integer NOT NULL,
    sha256 char(64) NOT NULL,
    comment varchar(1000) NOT NULL DEFAULT '',
    submitted_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    is_late boolean NOT NULL,
    status varchar(10) NOT NULL DEFAULT 'SUBMITTED',
    marks numeric(6,2),
    feedback varchar(4000),
    evaluated_by bigint,
    evaluated_at timestamptz,
    CONSTRAINT uq_assignment_submission_college_id UNIQUE (college_id, id),
    CONSTRAINT uq_assignment_submission_attempt UNIQUE (assignment_id, student_id, attempt),
    CONSTRAINT ck_assignment_submission_attempt CHECK (attempt BETWEEN 1 AND 50),
    CONSTRAINT ck_assignment_submission_file CHECK (length(btrim(original_filename)) > 0
        AND file_format IN ('pdf', 'docx', 'pptx', 'xlsx', 'txt', 'jpg', 'png')
        AND byte_size BETWEEN 1 AND 10485760 AND sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_assignment_submission_status CHECK (status IN ('SUBMITTED', 'RETURNED', 'EVALUATED', 'SUPERSEDED')),
    CONSTRAINT ck_assignment_submission_marks CHECK (marks IS NULL OR marks >= 0),
    CONSTRAINT ck_assignment_submission_review CHECK (
        (status = 'SUBMITTED' AND marks IS NULL AND evaluated_by IS NULL AND evaluated_at IS NULL)
     OR (status = 'EVALUATED' AND marks IS NOT NULL AND evaluated_by IS NOT NULL AND evaluated_at IS NOT NULL)
     OR (status = 'RETURNED' AND marks IS NULL AND feedback IS NOT NULL AND evaluated_by IS NOT NULL
            AND evaluated_at IS NOT NULL)
     OR status = 'SUPERSEDED'),
    CONSTRAINT ck_assignment_submission_review_time CHECK (evaluated_at IS NULL OR evaluated_at >= submitted_at),
    CONSTRAINT fk_assignment_submission_assignment FOREIGN KEY (college_id, assignment_id)
        REFERENCES public.assignments (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_assignment_submission_student FOREIGN KEY (college_id, student_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_assignment_submission_evaluator FOREIGN KEY (college_id, evaluated_by)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT
);
-- One current (not superseded) attempt per student and assignment.
CREATE UNIQUE INDEX uq_assignment_submission_current
    ON public.assignment_submissions (assignment_id, student_id) WHERE status <> 'SUPERSEDED';
CREATE INDEX ix_assignment_submissions_assignment
    ON public.assignment_submissions (college_id, assignment_id, status);
CREATE INDEX ix_assignment_submissions_student
    ON public.assignment_submissions (college_id, student_id, id DESC);

-- Marks may never exceed the assignment's maximum marks, and maximum marks cannot change once work is marked.
CREATE FUNCTION public.check_assignment_marks() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    IF TG_TABLE_NAME = 'assignment_submissions' THEN
        IF NEW.marks IS NOT NULL AND NEW.marks > (SELECT a.max_marks FROM public.assignments a
                                                   WHERE a.college_id = NEW.college_id AND a.id = NEW.assignment_id) THEN
            RAISE EXCEPTION 'Marks exceed the maximum marks' USING ERRCODE = '23514';
        END IF;
    ELSIF NEW.max_marks IS DISTINCT FROM OLD.max_marks AND EXISTS (
            SELECT 1 FROM public.assignment_submissions s
            WHERE s.college_id = NEW.college_id AND s.assignment_id = NEW.id AND s.marks IS NOT NULL) THEN
        RAISE EXCEPTION 'Maximum marks cannot change after marking' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER assignment_submission_marks
    BEFORE INSERT OR UPDATE OF marks ON public.assignment_submissions
    FOR EACH ROW EXECUTE FUNCTION public.check_assignment_marks();
CREATE TRIGGER assignment_max_marks
    BEFORE UPDATE OF max_marks ON public.assignments
    FOR EACH ROW EXECUTE FUNCTION public.check_assignment_marks();

