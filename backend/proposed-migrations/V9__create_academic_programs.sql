CREATE TABLE public.academic_programs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    department_id bigint NOT NULL,
    code varchar(30) NOT NULL,
    name varchar(150) NOT NULL,
    CONSTRAINT fk_program_department_college FOREIGN KEY (college_id, department_id)
        REFERENCES public.departments (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_program_college_code UNIQUE (college_id, code),
    CONSTRAINT ck_program_code CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'),
    CONSTRAINT ck_program_name CHECK (name ~ '[^[:space:]]')
);

CREATE INDEX ix_program_department_code
    ON public.academic_programs (college_id, department_id, code);
