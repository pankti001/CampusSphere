-- Personal faculty notifications about their timetable lessons. Requires V12 faculty_profiles and V18 timetables.
-- Adds one new table and one trigger function; no existing table or row is changed.
--
-- Rows are written in the same transaction as a timetable publication or unpublication, so a failed publication
-- leaves no notifications. event_key identifies the publication event and lesson; the unique key makes a retried
-- event insert nothing twice. Notifications are history: only read_at may change, and rows cannot be deleted.
-- Lesson details are copied at the time of the event so the history stays accurate if names change later.

CREATE TABLE public.faculty_notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    timetable_id bigint NOT NULL,
    event_key varchar(100) NOT NULL,
    kind varchar(10) NOT NULL,
    title varchar(160) NOT NULL,
    body varchar(600) NOT NULL,
    subject_code varchar(30),
    subject varchar(150),
    program varchar(150) NOT NULL,
    semester varchar(150) NOT NULL,
    division varchar(150) NOT NULL,
    academic_year varchar(9) NOT NULL,
    day_of_week smallint NOT NULL,
    start_time time(0) NOT NULL,
    end_time time(0) NOT NULL,
    classroom_code varchar(30),
    starts_on date NOT NULL,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    read_at timestamptz,
    CONSTRAINT fk_faculty_notification_faculty FOREIGN KEY (college_id, faculty_id)
        REFERENCES public.faculty_profiles (college_id, faculty_id) ON DELETE RESTRICT,
    CONSTRAINT fk_faculty_notification_timetable FOREIGN KEY (college_id, timetable_id)
        REFERENCES public.timetables (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_faculty_notification_event UNIQUE (college_id, faculty_id, event_key),
    CONSTRAINT ck_faculty_notification_kind CHECK (kind IN ('ASSIGNED', 'CHANGED', 'REASSIGNED', 'CANCELLED')),
    CONSTRAINT ck_faculty_notification_text CHECK (title ~ '[^[:space:]]' AND body ~ '[^[:space:]]'),
    CONSTRAINT ck_faculty_notification_day CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT ck_faculty_notification_time CHECK (end_time > start_time),
    CONSTRAINT ck_faculty_notification_read CHECK (read_at IS NULL OR read_at >= created_at)
);

CREATE INDEX ix_faculty_notifications_inbox ON public.faculty_notifications (college_id, faculty_id, id DESC);
CREATE INDEX ix_faculty_notifications_unread ON public.faculty_notifications (college_id, faculty_id)
    WHERE read_at IS NULL;
CREATE INDEX ix_faculty_notifications_timetable ON public.faculty_notifications (college_id, timetable_id);

CREATE FUNCTION public.protect_faculty_notification() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Faculty notifications are kept as history' USING ERRCODE = '42501';
    END IF;
    IF (NEW.id, NEW.college_id, NEW.faculty_id, NEW.timetable_id, NEW.event_key, NEW.kind, NEW.title, NEW.body,
        NEW.subject_code, NEW.subject, NEW.program, NEW.semester, NEW.division, NEW.academic_year, NEW.day_of_week,
        NEW.start_time, NEW.end_time, NEW.classroom_code, NEW.starts_on, NEW.created_at)
       IS DISTINCT FROM
       (OLD.id, OLD.college_id, OLD.faculty_id, OLD.timetable_id, OLD.event_key, OLD.kind, OLD.title, OLD.body,
        OLD.subject_code, OLD.subject, OLD.program, OLD.semester, OLD.division, OLD.academic_year, OLD.day_of_week,
        OLD.start_time, OLD.end_time, OLD.classroom_code, OLD.starts_on, OLD.created_at)
       OR (OLD.read_at IS NOT NULL AND NEW.read_at IS DISTINCT FROM OLD.read_at) THEN
        RAISE EXCEPTION 'Only an unread notification can be marked as read' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER faculty_notifications_history
    BEFORE UPDATE OR DELETE ON public.faculty_notifications
    FOR EACH ROW EXECUTE FUNCTION public.protect_faculty_notification();
CREATE TRIGGER faculty_notifications_no_truncate
    BEFORE TRUNCATE ON public.faculty_notifications
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();
