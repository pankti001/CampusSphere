-- Requires V9 programs, V10 academic periods, and V11 offerings.
ALTER TABLE public.academic_programs
    ADD CONSTRAINT uq_program_college_department_id UNIQUE (college_id, department_id, id);
ALTER TABLE public.academic_semesters
    ADD CONSTRAINT uq_semester_college_program_year_id UNIQUE (college_id, program_id, academic_year_id, id);
ALTER TABLE public.academic_divisions
    ADD CONSTRAINT uq_division_college_program_year_id UNIQUE (college_id, program_id, academic_year_id, id);
ALTER TABLE public.academic_subjects
    ADD CONSTRAINT uq_subject_college_program_semester_id UNIQUE (college_id, program_id, semester_id, id);

CREATE TABLE public.faculty_profiles (
    college_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    department_id bigint NOT NULL,
    PRIMARY KEY (college_id, faculty_id),
    FOREIGN KEY (college_id, faculty_id) REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (college_id, department_id) REFERENCES public.departments (college_id, id) ON DELETE RESTRICT
);
CREATE INDEX ix_faculty_profiles_department ON public.faculty_profiles (college_id, department_id);

CREATE TABLE public.faculty_subject_assignments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    department_id bigint NOT NULL,
    program_id bigint NOT NULL,
    academic_year_id bigint NOT NULL,
    semester_id bigint NOT NULL,
    division_id bigint NOT NULL,
    subject_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    ended_at timestamptz,
    CHECK (ended_at IS NULL OR ended_at >= created_at),
    FOREIGN KEY (college_id, faculty_id)
        REFERENCES public.faculty_profiles (college_id, faculty_id) ON DELETE RESTRICT,
    FOREIGN KEY (college_id, department_id, program_id)
        REFERENCES public.academic_programs (college_id, department_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (college_id, program_id, academic_year_id, semester_id)
        REFERENCES public.academic_semesters (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (college_id, program_id, academic_year_id, division_id)
        REFERENCES public.academic_divisions (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (college_id, program_id, semester_id, subject_id)
        REFERENCES public.academic_subjects (college_id, program_id, semester_id, id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_faculty_assignment_active
    ON public.faculty_subject_assignments (college_id, faculty_id, division_id, subject_id)
    WHERE ended_at IS NULL;
CREATE INDEX ix_faculty_assignments_profile ON public.faculty_subject_assignments (college_id, faculty_id, id);
CREATE INDEX ix_faculty_assignments_program ON public.faculty_subject_assignments (college_id, department_id, program_id);
CREATE INDEX ix_faculty_assignments_semester ON public.faculty_subject_assignments (college_id, program_id, academic_year_id, semester_id);
CREATE INDEX ix_faculty_assignments_division ON public.faculty_subject_assignments (college_id, program_id, academic_year_id, division_id);
CREATE INDEX ix_faculty_assignments_subject ON public.faculty_subject_assignments (college_id, program_id, semester_id, subject_id);
