-- Requires the reviewed V9 academic_programs table.
ALTER TABLE public.academic_programs
    ADD CONSTRAINT uq_academic_programs_college_id UNIQUE (college_id, id);

CREATE TABLE public.academic_years (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL REFERENCES public.colleges (id) ON DELETE RESTRICT,
    code varchar(9) NOT NULL,
    name varchar(150) NOT NULL,
    CONSTRAINT uq_academic_year_college_id UNIQUE (college_id, id),
    CONSTRAINT uq_academic_year_college_code UNIQUE (college_id, code),
    CONSTRAINT ck_academic_year_code CHECK (
        CASE WHEN code ~ '^[1-9][0-9]{3}-[1-9][0-9]{3}$'
        THEN substring(code, 6, 4)::integer = substring(code, 1, 4)::integer + 1
        ELSE false END
    ),
    CONSTRAINT ck_academic_year_name CHECK (name ~ '[^[:space:]]')
);

CREATE TABLE public.academic_semesters (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    program_id bigint NOT NULL,
    academic_year_id bigint NOT NULL,
    semester_number smallint NOT NULL CHECK (semester_number BETWEEN 1 AND 99),
    name varchar(150) NOT NULL,
    CONSTRAINT fk_semester_program_college FOREIGN KEY (college_id, program_id)
        REFERENCES public.academic_programs (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_semester_year_college FOREIGN KEY (college_id, academic_year_id)
        REFERENCES public.academic_years (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_semester_scope_number UNIQUE (college_id, program_id, academic_year_id, semester_number),
    CONSTRAINT ck_academic_semester_name CHECK (name ~ '[^[:space:]]')
);
CREATE INDEX ix_semester_college_year
    ON public.academic_semesters (college_id, academic_year_id);
