-- Requires V9–V12 and the existing college, identity and department foundation.
CREATE TABLE public.student_college_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id bigint NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,
    college_id bigint NOT NULL REFERENCES public.colleges (id) ON DELETE RESTRICT,
    status varchar(8) NOT NULL DEFAULT 'PENDING',
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    reviewed_by bigint,
    reviewed_at timestamptz,
    CONSTRAINT fk_student_college_request_reviewer FOREIGN KEY (college_id, reviewed_by)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT ck_student_college_request_state CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL)
        OR (status IN ('APPROVED', 'REJECTED') AND reviewed_by IS NOT NULL
            AND reviewed_at IS NOT NULL AND reviewed_at >= created_at))
);
CREATE UNIQUE INDEX uq_student_college_request_pending
    ON public.student_college_requests (student_id) WHERE status = 'PENDING';
CREATE INDEX ix_student_college_request_history ON public.student_college_requests (student_id, id DESC);
CREATE INDEX ix_student_college_request_queue ON public.student_college_requests (college_id, status, id);
CREATE INDEX ix_student_college_request_reviewer ON public.student_college_requests (college_id, reviewed_by);

CREATE TABLE public.student_profiles (
    college_id bigint NOT NULL,
    student_id bigint NOT NULL,
    department_id bigint NOT NULL,
    PRIMARY KEY (college_id, student_id),
    CONSTRAINT fk_student_profile_account FOREIGN KEY (college_id, student_id)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_profile_department FOREIGN KEY (college_id, department_id)
        REFERENCES public.departments (college_id, id) ON DELETE RESTRICT
);
CREATE INDEX ix_student_profile_department ON public.student_profiles (college_id, department_id);

CREATE TABLE public.student_enrollments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    student_id bigint NOT NULL,
    department_id bigint NOT NULL,
    program_id bigint NOT NULL,
    academic_year_id bigint NOT NULL,
    semester_id bigint NOT NULL,
    division_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    ended_at timestamptz,
    CONSTRAINT ck_student_enrollment_end CHECK (ended_at IS NULL OR ended_at >= created_at),
    CONSTRAINT fk_student_enrollment_profile FOREIGN KEY (college_id, student_id)
        REFERENCES public.student_profiles (college_id, student_id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_enrollment_program FOREIGN KEY (college_id, department_id, program_id)
        REFERENCES public.academic_programs (college_id, department_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_enrollment_semester FOREIGN KEY (college_id, program_id, academic_year_id, semester_id)
        REFERENCES public.academic_semesters (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_student_enrollment_division FOREIGN KEY (college_id, program_id, academic_year_id, division_id)
        REFERENCES public.academic_divisions (college_id, program_id, academic_year_id, id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_student_enrollment_current
    ON public.student_enrollments (student_id) WHERE ended_at IS NULL;
CREATE INDEX ix_student_enrollment_history ON public.student_enrollments (college_id, student_id, id DESC);
CREATE INDEX ix_student_enrollment_program ON public.student_enrollments (college_id, department_id, program_id);
CREATE INDEX ix_student_enrollment_semester ON public.student_enrollments (college_id, program_id, academic_year_id, semester_id);
CREATE INDEX ix_student_enrollment_division ON public.student_enrollments (college_id, program_id, academic_year_id, division_id);
