-- PROPOSED, NOT APPLIED. Needs the project owner's approval before it is run on any database.
--
-- V26: Academic Resources - syllabus versions (with optional units) and previous-year question papers.
-- Requires V12 (faculty_subject_assignments, with uq_material_assignment_scope from V16) and V7
-- (reject_privileged_audit_mutation). Stores metadata only; PDFs live in the existing private file storage,
-- addressed by a random storage key, exactly like study materials. Adds four tables; no existing table, column or
-- row is changed.
--
--   syllabus_versions        a syllabus PDF for one subject, uploaded by a faculty member teaching that subject.
--                            The current version is the newest published one (worked out when read, never stored).
--   syllabus_units           optional unit-wise content of one version, entered by college staff
--   question_papers          a previous-year question paper for one subject, uploaded by a faculty member teaching it
--   academic_resource_events append-only history: uploads, edits, replaced files, archiving, moderation
--
-- Every upload carries the teaching assignment it was made through, so the database itself guarantees the uploader
-- taught that subject in that college.

CREATE TABLE public.syllabus_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    assignment_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    division_id bigint NOT NULL,
    subject_id bigint NOT NULL,
    title varchar(160) NOT NULL CHECK (length(btrim(title)) > 0),
    description varchar(2000) NOT NULL DEFAULT '',
    version_label varchar(40) NOT NULL CHECK (length(btrim(version_label)) > 0),
    effective_from date,
    original_filename varchar(200) NOT NULL CHECK (length(btrim(original_filename)) > 0),
    storage_key uuid NOT NULL UNIQUE,
    byte_size integer NOT NULL CHECK (byte_size BETWEEN 1 AND 10485760),
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    status varchar(9) NOT NULL DEFAULT 'PUBLISHED' CHECK (status IN ('PUBLISHED', 'ARCHIVED', 'HIDDEN', 'REMOVED')),
    moderation_note varchar(500),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_syllabus_version_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_syllabus_version_times CHECK (updated_at >= created_at),
    CONSTRAINT ck_syllabus_version_moderation CHECK (status NOT IN ('HIDDEN', 'REMOVED') OR moderation_note IS NOT NULL),
    CONSTRAINT fk_syllabus_version_assignment
        FOREIGN KEY (college_id, assignment_id, faculty_id, division_id, subject_id)
        REFERENCES public.faculty_subject_assignments (college_id, id, faculty_id, division_id, subject_id) ON DELETE RESTRICT
);
-- A version label is used once per subject, and the same file is not uploaded twice for a subject.
CREATE UNIQUE INDEX uq_syllabus_version_label
    ON public.syllabus_versions (college_id, subject_id, lower(version_label)) WHERE status <> 'REMOVED';
CREATE UNIQUE INDEX uq_syllabus_version_file
    ON public.syllabus_versions (college_id, subject_id, sha256) WHERE status <> 'REMOVED';
CREATE INDEX ix_syllabus_versions_subject ON public.syllabus_versions (college_id, subject_id, id DESC);
CREATE INDEX ix_syllabus_versions_faculty ON public.syllabus_versions (college_id, faculty_id, id DESC);

CREATE TABLE public.syllabus_units (
    college_id bigint NOT NULL,
    version_id bigint NOT NULL,
    unit_number smallint NOT NULL CHECK (unit_number BETWEEN 1 AND 30),
    title varchar(160) NOT NULL CHECK (length(btrim(title)) > 0),
    description varchar(2000) NOT NULL DEFAULT '',
    topics varchar(4000) NOT NULL DEFAULT '',
    objectives varchar(2000) NOT NULL DEFAULT '',
    references_text varchar(2000) NOT NULL DEFAULT '',
    PRIMARY KEY (version_id, unit_number),
    CONSTRAINT fk_syllabus_unit_version FOREIGN KEY (college_id, version_id)
        REFERENCES public.syllabus_versions (college_id, id) ON DELETE CASCADE
);

CREATE TABLE public.question_papers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    assignment_id bigint NOT NULL,
    faculty_id bigint NOT NULL,
    division_id bigint NOT NULL,
    subject_id bigint NOT NULL,
    exam_type varchar(5) NOT NULL CHECK (exam_type IN ('MID1', 'MID2', 'FINAL', 'OTHER')),
    exam_type_label varchar(60),
    exam_year smallint NOT NULL CHECK (exam_year BETWEEN 1990 AND 2100),
    exam_session varchar(60) NOT NULL DEFAULT '',
    title varchar(160) NOT NULL CHECK (length(btrim(title)) > 0),
    description varchar(2000) NOT NULL DEFAULT '',
    original_filename varchar(200) NOT NULL CHECK (length(btrim(original_filename)) > 0),
    storage_key uuid NOT NULL UNIQUE,
    byte_size integer NOT NULL CHECK (byte_size BETWEEN 1 AND 10485760),
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    status varchar(9) NOT NULL DEFAULT 'PUBLISHED' CHECK (status IN ('PUBLISHED', 'ARCHIVED', 'HIDDEN', 'REMOVED')),
    moderation_note varchar(500),
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT uq_question_paper_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_question_paper_times CHECK (updated_at >= created_at),
    CONSTRAINT ck_question_paper_other_label CHECK ((exam_type = 'OTHER') = (exam_type_label IS NOT NULL)),
    CONSTRAINT ck_question_paper_moderation CHECK (status NOT IN ('HIDDEN', 'REMOVED') OR moderation_note IS NOT NULL),
    CONSTRAINT fk_question_paper_assignment
        FOREIGN KEY (college_id, assignment_id, faculty_id, division_id, subject_id)
        REFERENCES public.faculty_subject_assignments (college_id, id, faculty_id, division_id, subject_id) ON DELETE RESTRICT
);
CREATE UNIQUE INDEX uq_question_paper_file
    ON public.question_papers (college_id, subject_id, sha256) WHERE status <> 'REMOVED';
CREATE INDEX ix_question_papers_subject ON public.question_papers (college_id, subject_id, exam_year DESC, id DESC);
CREATE INDEX ix_question_papers_faculty ON public.question_papers (college_id, faculty_id, id DESC);
CREATE INDEX ix_question_papers_college ON public.question_papers (college_id, status, id DESC);

CREATE TABLE public.academic_resource_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    syllabus_version_id bigint,
    question_paper_id bigint,
    actor_id bigint NOT NULL,
    action varchar(9) NOT NULL CHECK (action IN ('UPLOAD', 'EDIT', 'REPLACE', 'UNITS', 'ARCHIVE', 'UNARCHIVE',
        'HIDE', 'RESTORE', 'REMOVE')),
    note varchar(500),
    occurred_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT ck_academic_resource_event_target CHECK ((syllabus_version_id IS NULL) <> (question_paper_id IS NULL)),
    CONSTRAINT fk_academic_resource_event_syllabus FOREIGN KEY (college_id, syllabus_version_id)
        REFERENCES public.syllabus_versions (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_academic_resource_event_paper FOREIGN KEY (college_id, question_paper_id)
        REFERENCES public.question_papers (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_academic_resource_event_actor FOREIGN KEY (college_id, actor_id)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT
);
CREATE INDEX ix_academic_resource_events_syllabus ON public.academic_resource_events (college_id, syllabus_version_id, id)
    WHERE syllabus_version_id IS NOT NULL;
CREATE INDEX ix_academic_resource_events_paper ON public.academic_resource_events (college_id, question_paper_id, id)
    WHERE question_paper_id IS NOT NULL;
CREATE INDEX ix_academic_resource_events_time ON public.academic_resource_events (college_id, occurred_at DESC);
CREATE TRIGGER academic_resource_events_append_only
    BEFORE UPDATE OR DELETE OR TRUNCATE ON public.academic_resource_events
    FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();
