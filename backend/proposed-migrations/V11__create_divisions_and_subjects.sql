-- Requires V9 programs and V10 academic periods.
ALTER TABLE public.academic_semesters
    ADD CONSTRAINT uq_semester_college_program_id UNIQUE (college_id, program_id, id);

CREATE TABLE public.academic_divisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    program_id bigint NOT NULL,
    academic_year_id bigint NOT NULL,
    code varchar(30) NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'),
    name varchar(150) NOT NULL CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT fk_division_program_college FOREIGN KEY (college_id, program_id)
        REFERENCES public.academic_programs (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_division_year_college FOREIGN KEY (college_id, academic_year_id)
        REFERENCES public.academic_years (college_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_division_scope_code UNIQUE (college_id, program_id, academic_year_id, code)
);

CREATE INDEX ix_division_college_year ON public.academic_divisions (college_id, academic_year_id);

CREATE TABLE public.academic_subjects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL,
    program_id bigint NOT NULL,
    semester_id bigint NOT NULL,
    code varchar(30) NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'),
    name varchar(150) NOT NULL CHECK (name ~ '[^[:space:]]'),
    CONSTRAINT fk_subject_program_semester FOREIGN KEY (college_id, program_id, semester_id)
        REFERENCES public.academic_semesters (college_id, program_id, id) ON DELETE RESTRICT,
    CONSTRAINT uq_subject_scope_code UNIQUE (college_id, program_id, semester_id, code)
);
