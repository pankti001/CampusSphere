CREATE TABLE public.colleges (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(30) NOT NULL UNIQUE,
    name varchar(150) NOT NULL,
    is_active boolean NOT NULL DEFAULT true
);

ALTER TABLE public.users
    ADD COLUMN college_id bigint REFERENCES public.colleges (id) ON DELETE RESTRICT,
    ADD CONSTRAINT uq_users_college_id UNIQUE (college_id, id);

ALTER TABLE public.faculty_access_requests
    ADD COLUMN college_id bigint REFERENCES public.colleges (id) ON DELETE RESTRICT,
    ADD CONSTRAINT fk_faculty_request_college_applicant
        FOREIGN KEY (college_id, applicant_id)
        REFERENCES public.users (college_id, id) ON DELETE RESTRICT;

CREATE INDEX ix_faculty_request_college_status
    ON public.faculty_access_requests (college_id, status, id);

