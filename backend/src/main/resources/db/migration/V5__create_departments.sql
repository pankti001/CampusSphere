CREATE TABLE public.departments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL REFERENCES public.colleges (id) ON DELETE RESTRICT,
    code varchar(30) NOT NULL,
    name varchar(150) NOT NULL,
    CONSTRAINT uq_departments_college_code UNIQUE (college_id, code),
    CONSTRAINT uq_departments_college_id UNIQUE (college_id, id),
    CONSTRAINT ck_departments_code CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'),
    CONSTRAINT ck_departments_name CHECK (name ~ '[^[:space:]]')
);
