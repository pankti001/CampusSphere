CREATE UNIQUE INDEX uq_users_normalized_email ON public.users (lower(btrim(email)));

CREATE TABLE public.college_registration_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL,
    code varchar(30) NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,29}$'),
    website varchar(250),
    full_name varchar(100) NOT NULL,
    email varchar(150) NOT NULL CHECK (email = lower(btrim(email))),
    position varchar(100) NOT NULL,
    password_hash varchar(255),
    status varchar(8) NOT NULL DEFAULT 'PENDING',
    submitted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP + interval '720 hours',
    CHECK (expires_at = submitted_at + interval '720 hours'),
    reviewer_id bigint REFERENCES public.users(id),
    decided_at timestamptz,
    verification_method varchar(80),
    institution_verified boolean NOT NULL DEFAULT false,
    representative_verified boolean NOT NULL DEFAULT false,
    mailbox_verified boolean NOT NULL DEFAULT false,
    verified_at timestamptz,
    rejection_reason varchar(300),
    college_id bigint UNIQUE REFERENCES public.colleges(id),
    admin_id bigint UNIQUE,
    FOREIGN KEY (college_id, admin_id) REFERENCES public.users(college_id,id),
    CHECK (password_hash ~ '[^[:space:]]'),
    CHECK (rejection_reason ~ '[^[:space:]]'),
    CHECK (verification_method IN ('OFFICIAL_CALLBACK','OFFICIAL_EMAIL')),
    CHECK (decided_at >= submitted_at),
    CHECK (status <> 'EXPIRED' OR decided_at = expires_at),
    CHECK (status NOT IN ('APPROVED','REJECTED') OR decided_at < expires_at),
    CHECK (verified_at = decided_at),
    CHECK ((status = 'PENDING') = (password_hash IS NOT NULL)),
    CHECK ((status IN ('APPROVED','REJECTED')) = (reviewer_id IS NOT NULL)),
    CHECK ((status <> 'PENDING') = (decided_at IS NOT NULL)),
    CHECK ((status = 'REJECTED') = (rejection_reason IS NOT NULL)),
    CHECK ((status = 'APPROVED') = (college_id IS NOT NULL)),
    CHECK ((status = 'APPROVED') = (admin_id IS NOT NULL)),
    CHECK ((status = 'APPROVED') = (verification_method IS NOT NULL)),
    CHECK ((status = 'APPROVED') = (verified_at IS NOT NULL)),
    CHECK ((status = 'APPROVED') = institution_verified AND institution_verified = representative_verified
        AND representative_verified = mailbox_verified),
    CHECK (status IN ('PENDING','APPROVED','REJECTED','EXPIRED'))
);
CREATE UNIQUE INDEX uq_pending_registration_code ON public.college_registration_requests(code) WHERE status='PENDING';
CREATE UNIQUE INDEX uq_pending_registration_email ON public.college_registration_requests(email) WHERE status='PENDING';
CREATE INDEX ix_registration_queue ON public.college_registration_requests(status,id);
CREATE INDEX ix_registration_expiry ON public.college_registration_requests(expires_at) WHERE status='PENDING';

