CREATE TABLE public.faculty_access_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    applicant_id bigint NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,
    status varchar(8) NOT NULL DEFAULT 'PENDING',
    reviewer_id bigint REFERENCES public.users (id) ON DELETE RESTRICT,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at timestamp with time zone,
    CONSTRAINT ck_faculty_request_decision CHECK (
        (status = 'PENDING' AND reviewer_id IS NULL AND decided_at IS NULL)
        OR (status IN ('APPROVED', 'REJECTED') AND reviewer_id IS NOT NULL
            AND reviewer_id <> applicant_id AND decided_at IS NOT NULL)
    )
);

CREATE INDEX ix_faculty_request_applicant_history
    ON public.faculty_access_requests (applicant_id, id DESC);

CREATE UNIQUE INDEX uq_faculty_request_pending
    ON public.faculty_access_requests (applicant_id) WHERE status = 'PENDING';
