CREATE TABLE public.college_admin_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_id bigint NOT NULL REFERENCES public.colleges (id) ON DELETE RESTRICT,
    email varchar(150) NOT NULL CHECK (email = lower(btrim(email)) AND email <> ''),
    token_hash bytea NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
    issued_by bigint NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL CHECK (expires_at = created_at + interval '24 hours'),
    accepted_at timestamptz,
    accepted_by bigint,
    revoked_at timestamptz,
    revoked_by bigint REFERENCES public.users (id) ON DELETE RESTRICT,
    expired_at timestamptz,
    FOREIGN KEY (college_id, accepted_by) REFERENCES public.users (college_id, id) ON DELETE RESTRICT,
    CHECK ((accepted_at IS NULL) = (accepted_by IS NULL)),
    CHECK ((revoked_at IS NULL) = (revoked_by IS NULL)),
    CHECK (num_nonnulls(accepted_at, revoked_at, expired_at) <= 1),
    CHECK (accepted_at IS NULL OR (accepted_at >= created_at AND accepted_at < expires_at)),
    CHECK (revoked_at IS NULL OR (revoked_at >= created_at AND revoked_at < expires_at)),
    CHECK (expired_at IS NULL OR expired_at = expires_at)
);

CREATE UNIQUE INDEX uq_college_admin_invitations_open
    ON public.college_admin_invitations (college_id, email)
    WHERE accepted_at IS NULL AND revoked_at IS NULL AND expired_at IS NULL;
CREATE INDEX ix_college_admin_invitations_college_history
    ON public.college_admin_invitations (college_id, id DESC);

CREATE TABLE public.privileged_audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id bigint NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT,
    action varchar(40) NOT NULL CHECK (action IN (
        'SUPER_ADMIN_PROVISIONED', 'COLLEGE_CREATED', 'COLLEGE_UPDATED',
        'COLLEGE_ACTIVATED', 'COLLEGE_DEACTIVATED',
        'INVITATION_ISSUED', 'INVITATION_ACCEPTED', 'INVITATION_REVOKED'
    )),
    target_id bigint NOT NULL CHECK (target_id > 0),
    occurred_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE FUNCTION public.reject_privileged_audit_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Privileged audit events are append-only' USING ERRCODE = '42501';
END;
$$;

CREATE TRIGGER privileged_audit_append_only
BEFORE UPDATE OR DELETE OR TRUNCATE ON public.privileged_audit_events
FOR EACH STATEMENT EXECUTE FUNCTION public.reject_privileged_audit_mutation();
